#!/usr/bin/env python3
"""BF16 롤백용 agent-api 설정을 만든다 (agent-api 컨테이너 안에서 실행, PyYAML 필요).

rag_config_spark_vllm.yaml에서 llm.served_model_name과 llm.tokenizer_path 두 값만 바꾼다.
검색·프롬프트·샘플링은 그대로다. 출력은 번들 config/ (컨테이너 /bundle-config)에 두고
.env의 AGENT_CONFIG_PATH로 가리킨다(README §18).
"""

from __future__ import annotations

import argparse
import copy
import hashlib
import sys
from collections.abc import Mapping, Sequence
from pathlib import Path
from typing import Any

import yaml

DEFAULT_SOURCE = "/workspace/trainer/configs/rag_config_spark_vllm.yaml"
DEFAULT_SERVED_MODEL_NAME = "qwen36-27b-shipcoat-v6-1-bf16"
DEFAULT_TOKENIZER_PATH = "/output/merged/qwen36_27b_shipcoat_v6_1_bf16"
CHANGED_KEYS = (("llm", "served_model_name"), ("llm", "tokenizer_path"))


def render(config: Mapping[str, Any], *, served_model_name: str, tokenizer_path: str) -> dict[str, Any]:
    llm = config.get("llm")
    if not isinstance(llm, Mapping) or llm.get("backend") != "openai":
        raise ValueError("source config must use llm.backend: openai")
    rendered = copy.deepcopy(dict(config))
    rendered["llm"]["served_model_name"] = served_model_name
    rendered["llm"]["tokenizer_path"] = tokenizer_path
    return rendered


def _parse_args(argv: Sequence[str] | None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path, default=Path(DEFAULT_SOURCE))
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--served-model-name", default=DEFAULT_SERVED_MODEL_NAME)
    parser.add_argument("--tokenizer-path", default=DEFAULT_TOKENIZER_PATH)
    return parser.parse_args(argv)


def main(argv: Sequence[str] | None = None) -> int:
    args = _parse_args(argv)
    raw = args.source.read_bytes()
    config = yaml.safe_load(raw)
    try:
        rendered = render(config, served_model_name=args.served_model_name, tokenizer_path=args.tokenizer_path)
    except ValueError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 1
    header = (
        f"# generated by deploy/spark/scripts/render_rollback_config.py\n"
        f"# source: {args.source} sha256={hashlib.sha256(raw).hexdigest()}\n"
        f"# changed: llm.served_model_name={args.served_model_name}, llm.tokenizer_path={args.tokenizer_path}\n"
    )
    body = yaml.safe_dump(rendered, allow_unicode=True, sort_keys=False, width=1000)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(header + body, encoding="utf-8")
    print(args.output)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
