def wants_simulator_context(prompt: str) -> bool:
    """대화 경로: 도장 낱말이나 기록 표지가 있는 질문만. 주제 밖 잡담은 지금처럼 둔다."""
    return is_domain_question(prompt) or has_record_marker(prompt)
